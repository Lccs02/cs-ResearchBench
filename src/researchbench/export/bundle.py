"""Atomic report bundles with validation, provenance and explicit uncertainty."""
import hashlib
from importlib.metadata import version
import json
from pathlib import Path
import platform
import shutil
import tempfile
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from researchbench import __version__
from researchbench.analysis.summary import CONTEXT, ablations, metric_rows, summarize
from researchbench.core.schema import canonical, write_records


def tex_escape(value):
    table = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(table.get(c, c) for c in str(value))


def latex_table(frame):
    # A standalone tabular per homogeneous group avoids mixing units/protocols.
    lines = ["% Generated by ResearchBench. Unverified; synthetic rows are demonstrations.", "% Requires \\usepackage{booktabs}. See manifest.json and records.json for provenance."]
    for context, group in frame.groupby(CONTEXT, sort=True, dropna=False):
        label = dict(zip(CONTEXT, context))
        lines += [r"\begin{tabular}{lrrl}", r"\toprule",
                  r"\multicolumn{4}{l}{" + tex_escape(f"{label['project']} / {label['dataset']} / {label['split']} / {label['metric']} ({label['unit']})") + r"} \\",
                  r"\multicolumn{4}{l}{" + tex_escape(f"{label['evaluation_id']} | {label['data_kind']} | Unverified") + r"} \\",
                  r"\multicolumn{4}{l}{" + tex_escape(f"Protocol: {label['protocol_id'][:12]} | seed std, ddof=1") + r"} \\",
                  r"Model & Mean & Std & Seeds \\", r"\midrule"]
        for row in group.itertuples():
            std = "Unverified" if pd.isna(row.std) else f"{row.std:.6g}"
            lines.append(f"{tex_escape(row.model)} & {row.mean:.6g} & {std} & {row.n_seeds} " + r"\\")
        lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


def _plot_summary(summary, out):
    figures = []
    for index, (values, group) in enumerate(summary.groupby(CONTEXT, sort=True, dropna=False)):
        context = dict(zip(CONTEXT, values))
        fig, ax = plt.subplots(figsize=(max(6, len(group) * 1.3), 4.2))
        x = np.arange(len(group))
        ax.bar(x, group["mean"], color="#4477AA", alpha=0.9)
        valid_std = group["std"].notna().to_numpy()
        if valid_std.any():
            ax.errorbar(x[valid_std], group.loc[valid_std, "mean"], yerr=group.loc[valid_std, "std"], fmt="none", color="#222222", capsize=4)
        ax.set_xticks(x, group.model, rotation=15, ha="right")
        ax.set_ylabel(f"{context['metric']} ({context['unit']})")
        ax.set_title(f"{context['dataset']} / {context['split']} / {context['evaluation_id']}\n{context['data_kind']} · Unverified", fontsize=10)
        fig.text(0.5, 0.01, "Equal-seed mean; bars: sample std (ddof=1), omitted for n<2", ha="center", fontsize=8)
        fig.tight_layout(rect=(0, .04, 1, 1))
        name = f"summary_{index:03d}.png"
        fig.savefig(out / name, dpi=160, metadata={"Software": f"ResearchBench {__version__}", "Description": canonical(context)})
        plt.close(fig)
        figures.append({"file": name, "context": context, "run_ids": group.run_ids.tolist()})
    return figures


def export_bundle(records, output: Path, *, baseline=None):
    """Output must not exist. Build in a sibling staging directory, then rename."""
    output = Path(output)
    if output.exists():
        raise ValueError(f"Output already exists: {output}; choose a new directory")
    rows, summary = metric_rows(records), summarize(records)
    differences = ablations(records, baseline) if baseline is not None else None
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".researchbench-", dir=output.parent))
    try:
        write_records(records, staging / "records.json")
        rows.to_csv(staging / "metrics.csv", index=False, na_rep="Unverified")
        summary.to_csv(staging / "summary.csv", index=False, na_rep="Unverified")
        (staging / "summary.tex").write_text(latex_table(summary), encoding="utf-8")
        if differences is not None:
            differences.to_csv(staging / "ablations.csv", index=False, na_rep="Unverified")
        figures = _plot_summary(summary, staging)
        manifest = {"schema_version": "1.0", "researchbench_version": __version__,
                    "validation": "Passed: structure and numerical contracts only",
                    "verification": "Unverified", "baseline": baseline,
                    "statistical_unit": "seed", "seed_weighting": "equal", "std_ddof": 1,
                    "warning": "Synthetic data are demonstrations, never paper results. Source truth and evaluation equivalence remain Unverified.",
                    "environment": {"python": platform.python_version(), **{name: version(name) for name in ("numpy", "pandas", "PyYAML", "matplotlib")}},
                    "figures": figures,
                    "runs": {r.run_id: {"sources": r.sources, "config": r.config, "protocol": r.protocol, "data_kind": r.data_kind} for r in records},
                    "artifacts": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(staging.iterdir()) if p.is_file()}}
        (staging / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
        staging.rename(output)
    except Exception:
        shutil.rmtree(staging)
        raise
    return output
